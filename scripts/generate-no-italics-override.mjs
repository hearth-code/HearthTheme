import { existsSync, readFileSync, writeFileSync } from 'fs'
import { pathToFileURL } from 'url'
import { buildProductMetadata } from './product-metadata.mjs'

const OUTPUT_PATH = 'docs/disable-italics.md'

function writeIfChanged(path, content) {
  if (existsSync(path)) {
    const prev = readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
    const next = content.replace(/\r\n/g, '\n')
    if (prev === next) return false
  }
  writeFileSync(path, content)
  return true
}

function hasItalic(fontStyle) {
  return /\bitalic\b/i.test(String(fontStyle || ''))
}

function stripItalic(fontStyle) {
  return String(fontStyle || '')
    .split(/\s+/)
    .filter((token) => token && token.toLowerCase() !== 'italic')
    .join(' ')
}

function toScopeList(scope) {
  if (Array.isArray(scope)) {
    return scope.map((entry) => String(entry).trim()).filter(Boolean)
  }
  if (typeof scope === 'string') {
    return scope
      .split(',')
      .map((entry) => entry.trim())
      .filter(Boolean)
  }
  return []
}

function collectItalicTextMateScopes(theme, themeLabel, scopeStyleMap) {
  const rules = Array.isArray(theme.tokenColors) ? theme.tokenColors : []
  for (const rule of rules) {
    const fontStyle = rule?.settings?.fontStyle
    if (!hasItalic(fontStyle)) continue
    const scopes = toScopeList(rule.scope)
    if (scopes.length === 0) {
      throw new Error(
        `generate-no-italics-override: "${themeLabel}" has an italic tokenColors rule without scopes; a scoped override cannot neutralize it`
      )
    }
    const replacement = stripItalic(fontStyle)
    for (const scope of scopes) {
      const existing = scopeStyleMap.get(scope)
      if (existing != null && existing !== replacement) {
        throw new Error(
          `generate-no-italics-override: scope "${scope}" maps to conflicting non-italic styles ("${existing}" vs "${replacement}") across published themes`
        )
      }
      scopeStyleMap.set(scope, replacement)
    }
  }
}

function collectItalicSemanticSelectors(theme, semanticSelectors) {
  const entries = theme.semanticTokenColors && typeof theme.semanticTokenColors === 'object' ? theme.semanticTokenColors : {}
  for (const [selector, value] of Object.entries(entries)) {
    if (!value || typeof value !== 'object') continue
    if (!hasItalic(value.fontStyle)) continue
    semanticSelectors.add(selector)
  }
}

export function buildNoItalicsOverride() {
  const metadata = buildProductMetadata()
  const themes = metadata.extension.themes
  if (!Array.isArray(themes) || themes.length === 0) {
    throw new Error('generate-no-italics-override: no published extension themes found')
  }

  const scopeStyleMap = new Map()
  const semanticSelectors = new Set()
  for (const entry of themes) {
    const themePath = String(entry.path || '').replace(/^\.\//, '')
    const theme = JSON.parse(readFileSync(themePath, 'utf8'))
    collectItalicTextMateScopes(theme, entry.label, scopeStyleMap)
    collectItalicSemanticSelectors(theme, semanticSelectors)
  }

  const labels = themes.map((entry) => entry.label)
  const themeKey = labels.map((label) => `[${label}]`).join('')

  const scopesByReplacement = new Map()
  for (const [scope, replacement] of scopeStyleMap.entries()) {
    if (!scopesByReplacement.has(replacement)) scopesByReplacement.set(replacement, [])
    scopesByReplacement.get(replacement).push(scope)
  }

  const textMateRules = [...scopesByReplacement.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([replacement, scopes]) => ({
      name: replacement
        ? `HearthCode italics off (keep ${replacement})`
        : 'HearthCode italics off',
      scope: scopes,
      settings: { fontStyle: replacement },
    }))

  const semanticRules = Object.fromEntries(
    [...semanticSelectors].map((selector) => [selector, { italic: false }])
  )

  const settings = {
    'editor.tokenColorCustomizations': {
      [themeKey]: { textMateRules },
    },
    'editor.semanticTokenColorCustomizations': {
      [themeKey]: {
        enabled: true,
        rules: semanticRules,
      },
    },
  }

  return { labels, themeKey, settings, scopeStyleMap, semanticSelectors }
}

function renderDoc(override) {
  const { labels, settings } = override
  const snippet = JSON.stringify(settings, null, 2)
  const labelList = labels.map((label) => `\`${label}\``).join(', ')

  return `<!-- Auto-generated by scripts/generate-no-italics-override.mjs - DO NOT EDIT -->

# Disable Italics

HearthCode uses italics for comments, types, and decorators. If your editor font has no true italic cut (common for CJK fonts, which fall back to a slanted fake oblique), you can turn italics off without leaving the theme.

VS Code has no global "disable italics" switch, but it supports per-theme user overrides. The snippet below mirrors the exact italic rules shipped in ${labelList}, so it neutralizes every italic style while keeping all colors and the rest of the styling intact.

## How to apply

1. Open the Command Palette and run **Preferences: Open User Settings (JSON)**.
2. Merge the two top-level keys below into your \`settings.json\`. If a key already exists, merge the theme-scoped blocks into it.

\`\`\`json
${snippet}
\`\`\`

## How to revert

Delete the two \`[HearthCode …]\` blocks from your \`settings.json\`.

## Notes

- The override is scoped to the HearthCode themes, so it does not affect any other theme you switch to.
- This file is generated from the shipped theme definitions. When theme italic rules change, the snippet is regenerated to match, so it never goes stale.
`
}

export function generateNoItalicsOverride() {
  const override = buildNoItalicsOverride()
  const changed = writeIfChanged(OUTPUT_PATH, renderDoc(override))
  console.log(`${changed ? '✓ generated' : '- unchanged'} ${OUTPUT_PATH}`)
  return override
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateNoItalicsOverride()
}
